-- Keep the existing public tables and their PostgREST response shapes.
create schema if not exists app_private;
revoke all on schema app_private from public;
grant usage on schema app_private to authenticated;

create function app_private.is_tu_google_user()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from auth.users as u
        join auth.identities as i on i.user_id = u.id
        where u.id = auth.uid()
          and u.email_confirmed_at is not null
          and lower(u.email) ~ '^[^@]+@(tu[.]ac[.]th|dome[.]tu[.]ac[.]th)$'
          and i.provider = 'google'
          and lower(i.identity_data ->> 'email') = lower(u.email)
          and i.identity_data ->> 'email_verified' = 'true'
    );
$$;
revoke all on function app_private.is_tu_google_user() from public;
grant execute on function app_private.is_tu_google_user() to authenticated;

alter table public.places add column if not exists is_mock boolean not null default false;
create table public.events (
    id bigint generated by default as identity primary key,
    title text not null,
    description text not null,
    location text not null,
    category text not null,
    "dateTime" text,
    start_at timestamptz not null,
    end_at timestamptz not null,
    user_id uuid not null default auth.uid(),
    image_url text,
    lat double precision,
    lng double precision,
    created_at timestamptz not null default now(),
    constraint events_valid_window check (
        isfinite(start_at) and isfinite(end_at) and end_at > start_at
    )
);

alter table public.places alter column rating set default 0;
