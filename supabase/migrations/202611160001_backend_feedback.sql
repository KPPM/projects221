alter table public.reviews
    add constraint reviews_valid_submission check (
        place_id is not null and rating is not null and rating between 1 and 5
        and comment is not null and btrim(comment) <> ''
    ) not valid,
    add constraint reviews_existing_place foreign key (place_id)
        references public.places(id) not valid;

create index if not exists reviews_place_id_idx on public.reviews(place_id);

create function app_private.refresh_place_review_stats()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    previous_place public.places.id%type;
    next_place public.places.id%type;
    place_key public.places.id%type;
    average numeric;
    total bigint;
begin
    if tg_op <> 'INSERT' then previous_place := old.place_id; end if;
    if tg_op <> 'DELETE' then next_place := new.place_id; end if;

    -- Serialize recalculation on each place. The aggregate runs after the lock,
    -- so a concurrent writer's committed review is included at READ COMMITTED.
    for place_key in
        select p.id from public.places as p
        where p.id in (previous_place, next_place)
        order by p.id
        for no key update
    loop
        select coalesce(round(avg(r.rating::numeric), 1), 0), count(*)
          into average, total
        from public.reviews as r
        where r.place_id = place_key
          and r.rating between 1 and 5;

        update public.places set rating = average, review_count = total::text
        where id = place_key;
    end loop;
    return null;
end;
$$;
revoke all on function app_private.refresh_place_review_stats() from public;

create trigger backend_refresh_review_stats
after insert or delete or update of rating, place_id on public.reviews
for each row execute function app_private.refresh_place_review_stats();

with totals as (
    select p.id, coalesce(round(avg(r.rating::numeric), 1), 0) as rating,
           count(r.rating) as review_count
    from public.places as p
    left join public.reviews as r on r.place_id = p.id
        and r.rating between 1 and 5
    group by p.id
)
update public.places as p set rating = totals.rating, review_count = totals.review_count::text
from totals where totals.id = p.id;

-- Old clients supply only a Bangkok-local start date. Their events end at
-- the next Bangkok midnight. Current clients supply both timestamps.
create function app_private.set_event_window()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    if new.start_at is null and new."dateTime" ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}$' then
        new.start_at := new."dateTime"::timestamp at time zone 'Asia/Bangkok';
        if new.end_at is null then
            new.end_at := (date_trunc('day', new.start_at at time zone 'Asia/Bangkok') + interval '1 day')
                at time zone 'Asia/Bangkok';
        end if;
    end if;
    return new;
end;
$$;
revoke all on function app_private.set_event_window() from public;
create trigger backend_set_event_window
before insert on public.events
for each row execute function app_private.set_event_window();

-- Old clients still PATCH the aggregate after inserting a review. Accept
-- those requests without allowing a browser to persist summary changes.
create function app_private.ignore_client_review_summary_update()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    if current_user = 'authenticated' then
        return null;
    end if;
    return new;
end;
$$;
revoke all on function app_private.ignore_client_review_summary_update() from public;
create trigger backend_protect_review_summary
before update on public.places
for each row execute function app_private.ignore_client_review_summary_update();

-- PostgREST computed field, requested as select=*,event_status.
create function public.event_status(event_row public.events)
returns text
language sql
stable
set search_path = ''
as $$
    select case
        when event_row.start_at is null or event_row.end_at is null
             or not isfinite(event_row.start_at) or not isfinite(event_row.end_at)
             or event_row.end_at <= event_row.start_at then 'pending'
        when statement_timestamp() >= event_row.end_at then 'expired'
        when statement_timestamp() < event_row.start_at then 'upcoming'
        else 'ongoing'
    end;
$$;
revoke all on function public.event_status(public.events) from public;
grant execute on function public.event_status(public.events) to anon, authenticated, service_role;

alter table public.places enable row level security;
alter table public.reviews enable row level security;
alter table public.events enable row level security;

grant select on public.places, public.reviews, public.events to anon, authenticated;
revoke insert, update, delete on public.places, public.reviews, public.events from anon, authenticated, public;
grant update (rating, review_count) on public.places to authenticated;
grant insert (name, category, "google map") on public.places to authenticated;
grant insert (place_id, user_name, user_avatar, rating, comment, image_urls) on public.reviews to authenticated;
grant insert (title, description, location, category, "dateTime", start_at, end_at, user_id)
    on public.events to authenticated;

-- Restrictive policies also constrain any pre-existing permissive policies.
create policy backend_places_read on public.places for select to anon, authenticated using (true);
create policy backend_places_no_mock on public.places as restrictive for select
    to anon, authenticated using (not is_mock);
create policy backend_reviews_read on public.reviews for select to anon, authenticated using (true);
create policy backend_reviews_visible_place on public.reviews as restrictive for select
    to anon, authenticated using (exists (
        select 1 from public.places where id = reviews.place_id
    ));
create policy backend_events_read on public.events for select to anon, authenticated using (true);
create policy backend_events_not_expired on public.events as restrictive for select
    to anon, authenticated using (public.event_status(events) <> 'expired');

create policy backend_places_insert on public.places for insert to authenticated with check (true);
create policy backend_places_owner on public.places as restrictive for insert
    to authenticated with check (
        (select app_private.is_tu_google_user())
        and not is_mock and rating = 0 and review_count = '0'
        and nullif(btrim(name), '') is not null
        and category in ('คาเฟ่', 'ร้านอาหาร', 'ของหวาน')
        and "google map" ~ '^https://www[.]google[.]com/maps/search/[?]api=1&query=-?[0-9]{1,2}([.][0-9]+)?,-?[0-9]{1,3}([.][0-9]+)?$'
        and abs(substring("google map" from 'query=(-?[0-9]{1,2}(?:[.][0-9]+)?),')::numeric) <= 90
        and abs(substring("google map" from ',(-?[0-9]{1,3}(?:[.][0-9]+)?)$')::numeric) <= 180
    );
create policy backend_reviews_insert on public.reviews for insert to authenticated with check (true);
create policy backend_reviews_owner on public.reviews as restrictive for insert
    to authenticated with check (
        (select app_private.is_tu_google_user())
        and exists (select 1 from public.places where id = reviews.place_id)
    );
create policy backend_events_insert on public.events for insert to authenticated with check (true);
create policy backend_events_owner on public.events as restrictive for insert
    to authenticated with check (
        (select app_private.is_tu_google_user()) and user_id = (select auth.uid())
        and btrim(title) <> '' and length(title) <= 100
        and btrim(description) <> '' and length(description) <= 500
        and btrim(location) <> '' and length(location) <= 150
        and category in ('food', 'sports', 'promo', 'concert')
    );

create policy backend_legacy_review_summary on public.places
    for update to authenticated
    using (not is_mock and (select app_private.is_tu_google_user()))
    with check (not is_mock and (select app_private.is_tu_google_user()));

-- Table grants and restrictive policies both matter if legacy roles have
-- column-level grants or inherit privileges.
do $$
declare
    table_name text;
begin
    foreach table_name in array array['places', 'reviews', 'events'] loop
        execute format('create policy backend_no_anon_insert on public.%I as restrictive for insert to anon with check (false)', table_name);
        if table_name <> 'places' then
            execute format('create policy backend_no_client_update on public.%I as restrictive for update to anon, authenticated using (false)', table_name);
        end if;
        execute format('create policy backend_no_client_delete on public.%I as restrictive for delete to anon, authenticated using (false)', table_name);
    end loop;
end;
$$;

notify pgrst, 'reload schema';
commit;
